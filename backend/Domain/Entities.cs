namespace MiningSystem.Domain;

public sealed class User
{
    public string Id { get; set; } = Guid.NewGuid().ToString("N");
    public string Name { get; set; } = "";
    public string Email { get; set; } = "";
    public string Role { get; set; } = Roles.Miner;
    public bool Active { get; set; } = true;
    public string PasswordHash { get; set; } = "";
    // Changing it invalidates every cookie and live connection issued before.
    public string SessionVersion { get; set; } = NewSessionVersion();
    public DateTime CreatedAt { get; set; }

    public static string NewSessionVersion() => Guid.NewGuid().ToString("N");
}

public sealed class MiningDevice
{
    public string Id { get; set; } = Guid.NewGuid().ToString("N");
    public string Name { get; set; } = "";
    public string Zone { get; set; } = "";
    public string? UserId { get; set; }
    public User? User { get; set; }
    public string KeyHash { get; set; } = "";
    public bool Active { get; set; } = true;
    public DateTime? LastSeenAt { get; set; }
    public DateTime CreatedAt { get; set; }

    public bool HasActiveMiner => User is { Active: true, Role: Roles.Miner };
}

public sealed class MiningMessage
{
    public long Id { get; set; }
    public string DeviceId { get; set; } = "";
    public MiningDevice Device { get; set; } = null!;
    public string ClientMessageId { get; set; } = "";
    public string Code { get; set; } = "";
    // Short context for automatic sensor alarms, e.g. "CO 245 ppm".
    public string? Detail { get; set; }
    // Preserve who wore the device and where it was, even after reassignment.
    public string MinerName { get; set; } = "";
    public string DeviceName { get; set; } = "";
    public string Zone { get; set; } = "";
    public DateTime SentAt { get; set; }
    public DateTime ReceivedAt { get; set; }
    public DateTime? ReviewedAt { get; set; }
    public string? ReviewedBy { get; set; }
}

public sealed class Reading
{
    public long Id { get; set; }
    public string DeviceId { get; set; } = "";
    public MiningDevice Device { get; set; } = null!;
    // Preserve who wore the device and where it was, even after reassignment.
    public string MinerName { get; set; } = "";
    public string DeviceName { get; set; } = "";
    public string Zone { get; set; } = "";
    // MLX90614 ambient temperature (tunnel air).
    public double? TemperatureC { get; set; }
    // MLX90614 object temperature (surface the sensor points at).
    public double? ObjectTemperatureC { get; set; }
    // SEN0564 (CO) values are only reported in ppm after calibration.
    public double? GasPpm { get; set; }
    public double? GasVoltage { get; set; }
    public double? BatteryPercent { get; set; }
    public string Level { get; set; } = AlertLevels.Normal;
    public bool Simulated { get; set; }
    public DateTime ReceivedAt { get; set; }
}

public sealed class AuditEvent
{
    public long Id { get; set; }
    public string Actor { get; set; } = "Sistema";
    public string Description { get; set; } = "";
    public DateTime CreatedAt { get; set; }
}

public sealed class VoiceMessage
{
    public long Id { get; set; }
    public string DeviceId { get; set; } = "";
    public MiningDevice Device { get; set; } = null!;
    public string ClientMessageId { get; set; } = "";
    public string MinerName { get; set; } = "";
    public string DeviceName { get; set; } = "";
    public string Zone { get; set; } = "";
    public DateTime RecordedAt { get; set; }
    public DateTime ReceivedAt { get; set; }
    public int DurationMs { get; set; }
    public int SampleRate { get; set; }
    public long SizeBytes { get; set; }
    // Relative to the voice directory; generated by the server, never by the client.
    public string StoragePath { get; set; } = "";
    public DateTime? ReviewedAt { get; set; }
    public string? ReviewedBy { get; set; }
}

public sealed class DeviceNotice
{
    public long Id { get; set; }
    public string DeviceId { get; set; } = "";
    public MiningDevice Device { get; set; } = null!;
    public string Code { get; set; } = "";
    public string DeviceName { get; set; } = "";
    public string? MinerName { get; set; }
    public string Zone { get; set; } = "";
    public string CreatedBy { get; set; } = "";
    public DateTime CreatedAt { get; set; }
    public DateTime ExpiresAt { get; set; }
    public DateTime? DeliveredAt { get; set; }
    public DateTime? ReadAt { get; set; }

    public string StatusAt(DateTime now) =>
        ReadAt is not null ? NoticeStatuses.Read
        : DeliveredAt is not null ? NoticeStatuses.Delivered
        : ExpiresAt <= now ? NoticeStatuses.Expired
        : NoticeStatuses.Pending;
}
